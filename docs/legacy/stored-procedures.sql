-- GetClosedAccounts


CREATE PROCEDURE [dbo].[GetClosedAccounts]
AS
BEGIN

 CREATE TABLE #TEMP_DEBTORACCOUNTS
     (
		 DCOUNT INT IDENTITY(1,1) NOT NULL,	
         DEBTORCODE nvarchar(50),
		 DEBTORNAME nvarchar(MAX),
         ACCOUNTNO int,
         AMOUNTOFADVANCE int
       
     )


 CREATE TABLE #TEMP_CLOSEDACCOUNTS
     (
		 CCOUNT INT IDENTITY(1,1) NOT NULL,	
         DEBTORCODE nvarchar(50),
		 DEBTORNAME nvarchar(MAX),
         ACCOUNTNO int,
         AMOUNTOFADVANCE int,
		 PAIDAMOUNT int,
         DUEAMOUNT int
       
     )

INSERT INTO #TEMP_DEBTORACCOUNTS(DEBTORCODE,DEBTORNAME,ACCOUNTNO,AMOUNTOFADVANCE)
SELECT DD.DEBTORCODE,DEBTORNAME,ACCOUNTNO,AMOUNTOFADVANCE from DAYWEISE_DEPOSITES as DD
inner join DEBTORS_MASTER as DM on DM.DEBTORCODE=DD.DEBTORCODE
where DM.ISACTIVE='True' and DD.ISACTIVE='True' and ACCOUNTSTATUS='OPEN' order by ACCOUNTNO

 DECLARE @MAXSCOUNT INT
 DECLARE @COUNT INT 
DECLARE @DEBTORCODE nvarchar(50)
DECLARE @DEBTORNAME nvarchar(MAx)
DECLARE @ACCOUNTNO int
DECLARE @AMOUNTOFADVANCE int
DECLARE @PAIDAMOUNT int 
DECLARE @DUEAMOUNT int 


SET @COUNT=1    
SELECT @MAXSCOUNT=COUNT(*) FROM #TEMP_DEBTORACCOUNTS 


 IF(@MAXSCOUNT>0)
     BEGIN
     WHILE(@COUNT<=@MAXSCOUNT) 
     BEGIN 
 
SELECT @DEBTORCODE=DEBTORCODE FROM  #TEMP_DEBTORACCOUNTS WHERE DCOUNT=@COUNT
SELECT @DEBTORNAME=DEBTORNAME FROM  #TEMP_DEBTORACCOUNTS WHERE DCOUNT=@COUNT
SELECT @ACCOUNTNO=ACCOUNTNO FROM  #TEMP_DEBTORACCOUNTS WHERE DCOUNT=@COUNT
SELECT @AMOUNTOFADVANCE=AMOUNTOFADVANCE FROM #TEMP_DEBTORACCOUNTS WHERE DCOUNT=@COUNT
SELECT @PAIDAMOUNT=sum(AMOUNT) from DAYWISE_PAYMENTS where DEBTORCODE=@DEBTORCODE and ACCOUNTNO=@ACCOUNTNO and ISACTIVE='TRUE'
set @DUEAMOUNT=@AMOUNTOFADVANCE-@PAIDAMOUNT

if(@DUEAMOUNT=0)
BEGIN

INSERT INTO #TEMP_CLOSEDACCOUNTS(DEBTORCODE,DEBTORNAME,ACCOUNTNO,AMOUNTOFADVANCE,PAIDAMOUNT,DUEAMOUNT)
values(@DEBTORCODE,@DEBTORNAME,@ACCOUNTNO,@AMOUNTOFADVANCE,@PAIDAMOUNT,@DUEAMOUNT)
END

SET @COUNT=@COUNT+1

END
END  
SELECT DEBTORCODE,DEBTORNAME,ACCOUNTNO,AMOUNTOFADVANCE,PAIDAMOUNT,DUEAMOUNT from #TEMP_CLOSEDACCOUNTS
end 
