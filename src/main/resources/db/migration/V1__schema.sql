-- Schema converted from SQL Server database RAJARAJESHWARI
-- (tables DEBTORS_MASTER, DAYWEISE_DEPOSITES, DAYWISE_PAYMENTS, Users, Roles_Master, DROPDOWN_MASTER)

CREATE TABLE roles (
    role_id     integer PRIMARY KEY,
    role_desc   varchar(50) NOT NULL,
    is_active   boolean NOT NULL DEFAULT true,
    reason      varchar(200)
);

CREATE TABLE users (
    user_id        integer PRIMARY KEY,
    username       varchar(50) NOT NULL UNIQUE,
    password_hash  varchar(100) NOT NULL,
    first_name     varchar(50),
    last_name      varchar(50),
    email          varchar(50),
    role_id        integer REFERENCES roles (role_id)
);

-- Look-up list for the "Note" field on a deposit (legacy DROPDOWN_MASTER NOTE/NOTEID)
CREATE TABLE note_types (
    note_id  integer PRIMARY KEY,
    note     varchar(100) NOT NULL
);

CREATE TABLE debtors (
    debtor_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debtor_code       varchar(50) NOT NULL UNIQUE,
    debtor_name       text NOT NULL,
    date_of_join      date NOT NULL,
    gender            char(1) NOT NULL,
    email             varchar(200),
    phone             varchar(100) NOT NULL,
    guarantor_name    text NOT NULL,
    guarantor_phone   varchar(100) NOT NULL,
    house_no          varchar(100) NOT NULL,
    street            varchar(100) NOT NULL,   -- also used as the "area" for collection routes
    seq               integer,                 -- visiting order inside the street/area
    city              varchar(100) NOT NULL,
    state             varchar(100) NOT NULL,
    pin               integer NOT NULL,
    guarantor_house_no varchar(100) NOT NULL,
    guarantor_street  varchar(100) NOT NULL,
    guarantor_city    varchar(100) NOT NULL,
    guarantor_state   varchar(100) NOT NULL,
    guarantor_pin     integer NOT NULL,
    photo             varchar(100) NOT NULL,
    user_id           integer NOT NULL,
    is_active         boolean NOT NULL DEFAULT true,
    deleted_by        text,
    delete_reason     text
);
CREATE INDEX ix_debtors_street ON debtors (street) WHERE is_active;
CREATE INDEX ix_debtors_user ON debtors (user_id);

CREATE SEQUENCE account_no_seq;

CREATE TABLE deposits (
    deposit_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debtor_code        varchar(100) NOT NULL REFERENCES debtors (debtor_code),
    account_no         integer NOT NULL UNIQUE,
    amount_of_advance  integer NOT NULL,        -- amount lent
    no_of_days         integer NOT NULL,
    day_of_payment     integer NOT NULL,        -- daily instalment
    date_of_advance    date NOT NULL,
    closing_date       date NOT NULL,
    note               integer NOT NULL,
    account_end_date   date,
    account_status     varchar(10) NOT NULL DEFAULT 'OPEN' CHECK (account_status IN ('OPEN','CLOSED')),
    user_id            integer NOT NULL,
    is_active          boolean NOT NULL DEFAULT true,
    deleted_by         text,
    delete_reason      text
);
CREATE INDEX ix_deposits_debtor ON deposits (debtor_code);
CREATE INDEX ix_deposits_date ON deposits (date_of_advance);

CREATE TABLE payments (
    payment_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    debtor_code   varchar(100) NOT NULL,
    account_no    integer NOT NULL,
    day_date      date NOT NULL,
    amount        integer NOT NULL,
    user_id       integer,
    is_active     boolean NOT NULL DEFAULT true,
    deleted_by    varchar(250),
    delete_reason varchar(500)
);
CREATE INDEX ix_payments_account ON payments (account_no, debtor_code);
CREATE INDEX ix_payments_date ON payments (day_date);
